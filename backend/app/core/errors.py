class UserFacingError(Exception):
    """Error whose message is safe to show to customers. Technical detail goes to server logs."""
    def __init__(self, user_message: str):
        super().__init__(user_message)
        self.user_message = user_message


class ExtractionError(UserFacingError): ...
class FetchError(UserFacingError): ...
class EmbeddingError(UserFacingError): ...
class ConfigError(UserFacingError): ...
